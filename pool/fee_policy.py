"""Bounded fee quotes for new payouts; signed retries never enter this builder."""
import re
import urllib.error

MAX_NANO = (1 << 63) - 1
MAX_ITERATIONS = 4


class FeeUnavailable(RuntimeError):
    pass


def policy(config):
    mode = config.get("payoutFeeMode", "fixed")
    if mode not in ("fixed", "auto"):
        raise ValueError("Payout fee mode must be fixed or auto")
    initial = config.get("payoutFeeNano")
    maximum = config.get("maximumPayoutFeeNano", initial if mode == "fixed" else 10_000_000)
    if type(initial) is not int or not 0 < initial <= MAX_NANO \
            or type(maximum) is not int or not initial <= maximum <= MAX_NANO:
        raise ValueError("Payout fee bounds must be positive protocol integers")
    return mode, initial, maximum


def quoted_fee(quote, tx, fee_script, paid_fee):
    if not isinstance(quote, dict) or type(quote.get("quoteVersion")) is not int or quote["quoteVersion"] != 1:
        raise FeeUnavailable("Native fee quote is unavailable; payouts are paused")
    values = []
    for name in ("feeNano", "minimumFeeNano", "paidFeeNano"):
        text = quote.get(name)
        if not isinstance(text, str) or not re.fullmatch(r"0|[1-9][0-9]{0,18}", text) or int(text) > MAX_NANO:
            raise FeeUnavailable("Native fee quote has invalid integer amounts; payouts are paused")
        values.append(int(text))
    size = quote.get("txSize")
    maximum_size = quote.get("maxTransactionSize")
    if type(size) is not int or type(maximum_size) is not int \
            or not 1 <= size <= maximum_size <= 4_194_304 or values[0] < values[1]:
        raise FeeUnavailable("Native fee quote has invalid size or floor; payouts are paused")
    if quote.get("txId") != tx.get("id") or quote.get("feeScriptHex") != fee_script or values[2] != paid_fee:
        raise FeeUnavailable("Native fee quote does not match the signed payout; payouts are paused")
    return values[0]


def prepare_payment(node, balances, plan):
    """Generate and validate a final signed batch before reserving any recipient's balance."""
    mode, fee, maximum = policy(node.config)
    minimum = node.config["minimumPayoutNano"]
    balance = None
    for _ in range(MAX_ITERATIONS):
        gross, amounts, charges = plan(balances, minimum, fee)
        if not amounts:
            return None
        if balance is None:
            balance = node.rpc("/wallet/balances")["balance"]
            if type(balance) is not int or not 0 <= balance <= MAX_NANO:
                raise FeeUnavailable("Native wallet balance is invalid; payouts are paused")
        if sum(gross.values()) > balance:
            return None
        tx = node.rpc("/wallet/transaction/generate", {
            "requests": [{"address": address, "value": amount} for address, amount in amounts.items()], "fee": fee})
        node.validate_payout(tx, amounts, fee)
        if mode == "fixed":
            return tx, gross, amounts, charges
        try:
            quote = node.rpc("/transactions/feeQuote?waitTime=1", tx)
        except urllib.error.HTTPError as error:
            if error.code != 404:
                raise
            # Old native nodes have no signed-size endpoint. Their configured fixed fee remains explicit.
            return tx, gross, amounts, charges
        required = quoted_fee(quote, tx, node.config["feeScriptHex"], fee)
        if required > maximum:
            raise FeeUnavailable("Estimated payout fee exceeds the configured maximum; credits remain accrued")
        if required <= fee:
            return tx, gross, amounts, charges
        # Repricing can change output encoding, change boxes and dust eligibility; quote the regenerated bytes.
        fee = required
    raise FeeUnavailable("Native payout fee did not stabilize; credits remain accrued")
